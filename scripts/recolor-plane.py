# Plane funnel colours (18/11/2026): the opt-in card and its screens in the colours of the plane, made with the same engine
# as scripts/recolor-burj.py (every blue moved by its role), scoped to theme="pl" (pl1/pl2/pl3 only for the board).
# Usage (repo root): python3 scripts/recolor-plane.py [palette ...]   palette: sky | gold | night
import importlib.util, sys
sp = importlib.util.spec_from_file_location('rb', 'scripts/recolor-burj.py'); rb = importlib.util.module_from_spec(sp); sp.loader.exec_module(rb)
PAL = {
  'sky':   (dict(main='#38b6ff', deep='#1a8fe0', light='#c4e8ff', mid='#80d0ff', dh=208, ds=1.0), '#04101e'),
  'gold':  (dict(main='#e3c27a', deep='#b8934a', light='#fff0c8', mid='#efd49a', dh=40, ds=0.5), '#0b0906'),
  'night': (dict(main='#ff8a1f', deep='#e0700f', light='#ffc37a', mid='#ffa95a', dh=222, ds=1.0), '#060c1f'),
}
args = sys.argv[1:] or ['night']
css = open('src/styles/optin.css').read()
out = ['/* Generated by scripts/recolor-plane.py (18/11): the opt-in in the colours of the plane, only with theme="pl" */']
for i, name in enumerate(args):
    P, bg = PAL[name]; cls = 'pl' if len(args) == 1 else f'pl{i + 1}'
    out += [rb.scoped(css, P, cls), f".oi-fade.oi-fade--{cls}{{background:radial-gradient(120% 90% at 50% 35%,{rb.move('#163266', P)} 0%,{rb.move('#0b1630', P)} 45%,{bg} 100%)}}"]
open('src/styles/optin-plane.css', 'w').write('\n'.join(out) + '\n')
print('ok css')
# the page behind the card: the stadium one with the plane words and pictures, its styles in the same colours
s = open('src/pages/the-stadium-blueprint.astro').read()
head, style = s[:s.index('<style is:global>')], s[s.index('<style is:global>'):]
head = head.replace('''// /the-stadium-blueprint (15/11/2026, Nico): the funnel for the stadium reel where you pick your own seat (word TICKET),
// copied from /the-towers-blueprint: only the opt-in card over the blurred stadium, it never closes, nothing behind it;
// after the form the free blueprint goes by email and the page moves on to /the-stadium-blueprint/watch (the face video
// with the stadium, the Full Stadium Blueprint at €5.99 and Everything we teach at €59). Blue like Towers.
// Images sd_* and PDFs: ~/Desktop/Studio Assets/06 Documents/Blueprint/Omnya Stadium Blueprint.''', '''// /the-plane-blueprint (18/11/2026, Nico): the funnel for the plane reels where you book your own seat (word PLANE),
// copied from /the-stadium-blueprint: only the opt-in card over the blurred plane, it never closes, nothing behind it;
// after the form the free blueprint downloads (no email) and the page moves on to /the-plane-blueprint/watch.
// Images pl_* and PDFs: ~/Desktop/Studio Assets/06 Documents/Blueprint/Omnya Plane Blueprint. Made by scripts/recolor-plane.py.''')
for a, b in [('How to build a stadium where you pick your own seat', 'How to build a plane where you pick your own seat'),
             ('Steal our stadium method: the free blueprint in five steps, and the Full Stadium Blueprint with every prompt, the 3D stadium code and the page where you pick your seat.',
              'Steal our plane method: the free blueprint in five steps, and the Full Plane Blueprint with every prompt, the 3D plane code and the page where you pick your seat.'),
             ('slug="the-stadium-blueprint" free="free-stadium"', 'slug="the-plane-blueprint" free="free-plane"'), ('word="Stadium"', 'word="Plane"'),
             ('watch="/the-stadium-blueprint/watch"', 'watch="/the-plane-blueprint/watch"'), ('/learn/sd_hero', '/learn/pl_hero')]:
    assert a in head, a; head = head.replace(a, b)
P, bg = PAL[args[0]]
# back from the stadium red to the Omnya blue, then into the plane colours
style = style.replace('#ff3b30', '#2997ff').replace('#d81f26', '#0a84ff').replace('255,59,48', '41,151,255').replace('#0a0505', '#05070a').replace('#170d0e', '#0d1117')
for i, name in enumerate(args):
    P, bg = PAL[name]; cls = 'pl' if len(args) == 1 else f'pl{i + 1}'
    h = head.replace('theme="sd"', f'theme="{cls}"').replace('/learn/sd_cover_book.webp', f'/learn/{cls}_cover_book.webp')
    out = 'src/pages/the-plane-blueprint.astro' if len(args) == 1 else f'src/pages/zz-{cls}.astro'
    open(out, 'w').write(h + rb.recolor(style, P).replace('#05070a', bg))
    print('ok page', out)

export type Lang = 'en' | 'it';
export const langs: Lang[] = ['en', 'it'];

export const langFromPath = (path: string): Lang => (path === '/it' || path.startsWith('/it/') ? 'it' : 'en');

/** "/it/work/x" → "/work/x" */
export const stripLang = (path: string) => path.replace(/^\/it(?=\/|$)/, '') || '/';

/** Same page in another language. */
export function localize(path: string, lang: Lang) {
  const base = stripLang(path).replace(/\/$/, '') || '/';
  if (lang === 'en') return base;
  return base === '/' ? '/it' : `/it${base}`;
}


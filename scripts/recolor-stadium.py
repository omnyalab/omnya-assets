# Stadium funnel colours (18/11/2026, Nico C1): the opt-in card and its screens in the red of the stadium seats, made with
# the same engine as scripts/recolor-burj.py (every blue moved by its role) and scoped to theme="sd".
# Usage (repo root): python3 scripts/recolor-stadium.py
import importlib.util
sp = importlib.util.spec_from_file_location('rb', 'scripts/recolor-burj.py'); rb = importlib.util.module_from_spec(sp); sp.loader.exec_module(rb)
P = dict(main='#ff3b30', deep='#d81f26', light='#ffb066', mid='#ff7a6e', dh=356, ds=1.0)
css = open('src/styles/optin.css').read()
out = ['/* Generated by scripts/recolor-stadium.py (18/11): the opt-in in the red of the stadium seats, only with theme="sd" */',
       rb.scoped(css, P, 'sd'),
       f".oi-fade.oi-fade--sd{{background:radial-gradient(120% 90% at 50% 35%,{rb.move('#163266', P)} 0%,{rb.move('#0b1630', P)} 45%,#0a0505 100%)}}"]
open('src/styles/optin-stadium.css', 'w').write('\n'.join(out) + '\n')
print('ok')

# the page behind the card (/the-stadium-blueprint): its own styles in the same red
p = 'src/pages/the-stadium-blueprint.astro'; s = open(p).read()
i = s.index('<style is:global>')
open(p, 'w').write(s[:i] + rb.recolor(s[i:], P).replace('#05070a', '#0a0505'))
print('ok page')

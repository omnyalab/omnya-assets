# Riyadh funnel colours (17/11/2026, Burj Al Ballur reels, word 3D), made like scripts/recolor-miami.py: the blue of the
# Stadium funnel becomes the colours of the real Burj Al Ballur photos (the violet LEDs of the tower, the amber street
# lights of Riyadh at night, the violet-navy night sky, the sunset gold). Every blue in a stylesheet is moved by its role: dark backgrounds take the night hue, the bright accent the
# main colour, the deep ends of gradients the deep colour, the pale ones the light colour. Card brand logos stay as they are.
# Usage (repo root): python3 scripts/recolor-burj.py [p1|p2|p3]
import re, sys, colorsys
PAL = {
  # P1 Ballur violet: the violet of the tower LEDs, amber city-light highlights, violet-night backgrounds
  'p1': dict(main='#9d5cff', deep='#6b3be0', light='#ffb066', mid='#c08cff', dh=260, ds=1.0),
  # P2 Riyadh amber: the amber of the street lights, violet highlights, the navy of the night sky
  'p2': dict(main='#ff9a3c', deep='#e0670f', light='#c9a8ff', mid='#ffbd70', dh=228, ds=1.0),
  # P3 sunset gold: the gold of the tower at sunset, peach highlights, the night blue
  'p3': dict(main='#f5b640', deep='#d98a1a', light='#ffcfa0', mid='#ff9a6a', dh=222, ds=1.0),
}
KEEP = {'#1434cb', '#1f72cd', '#0b4ea2', '#00447c', '#007b84', '#0079be', '#1a1f71', '#7c5cff'}
def rgb(h): return [int(h[i:i+2], 16) / 255 for i in (1, 3, 5)]
def hx(a): return '#' + ''.join('%02x' % max(0, min(255, round(x * 255))) for x in a)
def move(h6, P):
    if h6.lower() in KEEP: return h6
    r, g, b = rgb(h6); H, S, V = colorsys.rgb_to_hsv(r, g, b)
    if not (S > .12 and .5 < H < .7): return h6
    if V < .5 or S < .3:  # night backgrounds, lines, blue-grey text: same light, night hue
        return hx(colorsys.hsv_to_rgb(P['dh'] / 360, min(1, S * P['ds']), V))
    if S < .55: return P['light']
    if S < .8: return P['mid']
    if H * 360 >= 214 or V < .92: return P['deep']
    return P['main']
def recolor(s, P):
    def f(m):
        t = m.group(0); return move(t[:7], P) + t[7:]
    s = re.sub(r'#[0-9a-fA-F]{6}(?:[0-9a-fA-F]{2})?\b', f, s)
    def g(m):
        c = '#%02x%02x%02x' % tuple(int(x) for x in m.group(1, 2, 3)); n = move(c, P)
        return m.group(0) if n == c else 'rgba(%d,%d,%d,' % tuple(int(n[i:i+2], 16) for i in (1, 3, 5))
    return re.sub(r'rgba\((\d+),\s*(\d+),\s*(\d+),', g, s)

def blue_in(s, P):
    return recolor(s, P) != s

def rules(css):
    out, i = [], 0
    css = re.sub(r'/\*.*?\*/', '', css, flags=re.S); n = len(css)
    while i < n:
        j = css.find('{', i)
        if j < 0: break
        pre = css[i:j].strip(); depth, k = 1, j + 1
        while depth and k < n:
            depth += css[k] == '{'; depth -= css[k] == '}'; k += 1
        out.append((pre, css[j + 1:k - 1])); i = k
    return out

def scoped(css, P, cls):
    """The opt-in rules that carry a blue, recoloured and scoped to .oi--<cls> (the card) and its loading screen (.oil, the next sibling)."""
    res = []
    for pre, body in rules(css):
        if pre.startswith('@keyframes'): continue
        if pre.startswith('@media') or pre.startswith('@supports'):
            inner = scoped(body, P, cls)
            if inner: res.append(pre + '{' + inner + '}')
            continue
        if not blue_in(body, P): continue
        sels = []
        for s in pre.split(','):
            s = s.strip()
            if re.match(r'\.oidim(?![\w-])', s): sels.append(f'.oidim.oi--{cls}' + s[len('.oidim'):])
            elif re.match(r'\.oil(?![\w-])', s): sels.append(f'.oi--{cls} ~ ' + s)
            elif s.startswith('.oil'): sels.append(f'.oi--{cls} ~ .oil ' + s)
            elif s.startswith('.oi-fade'): continue
            else: sels.append(f'.oi--{cls} ' + s)
        sels = [x for x in sels if x]
        if sels: res.append(','.join(sels) + '{' + recolor(body, P) + '}')
    return '\n'.join(res)

if __name__ == '__main__':
    out = ['/* Generated by scripts/recolor-burj.py (17/11): the opt-in in the Burj Al Ballur colours, only with theme="ry…" */']
    css = open('src/styles/optin.css').read()
    for k in sys.argv[1:] or ['p1']:
        cls = 'ry' if len(sys.argv) <= 2 else 'ry' + k[1:]
        P = PAL[k]
        out.append(scoped(css, P, cls))
        fade = f"radial-gradient(120% 90% at 50% 35%,{move('#163266', P)} 0%,{move('#0b1630', P)} 45%,#07050f 100%)"
        out.append(f'.oi-fade.oi-fade--{cls}{{background:{fade}}}')
    open('src/styles/optin-burj.css', 'w').write('\n'.join(out) + '\n')
    print('ok')

# Build funnel in green (Nico 9/11, board C1): the blue of the x3 funnels (#2997ff and friends) becomes #22d35e
# on the Build pages only. Run once from the repo root; it rewrites:
#  - the style block of src/pages/the-build-blueprint.astro (that page's own CSS)
#  - src/views/sent/build.html (and its stylesheet, a green copy of public/learn/x3-sent.css)
#  - src/styles/optin-build.css: the opt-in rules that carry a colour, recoloured and prefixed with "body .oi--c1 ~ " / ".oi--c1",
#    so the card and the loading screen turn green only where OptIn gets theme="c1"
import re
MAIN = '#22d35e'
def rgb(h): return [int(h[i:i+2], 16) for i in (1, 3, 5)]
def hx(a): return '#' + ''.join('%02x' % max(0, min(255, round(x))) for x in a)
def shade(h, f): return hx([c * f for c in rgb(h)])
def tint(h, f): return hx([c + (255 - c) * f for c in rgb(h)])
def tintN(n, m):
    nb = max(rgb(n)) / 255; mm = rgb(m); mx = max(mm) or 1
    return hx([c / mx * nb * 255 * .85 + nb * 255 * .15 for c in mm])
NAVY = ['#12284e', '#080e1a', '#163266', '#0b1630', '#070b14', '#0b1220', '#0a1426', '#0f1a2e']
MAP = [('#2997ff', MAIN), ('#0071e3', shade(MAIN, .72)), ('#45a6ff', tint(MAIN, .25)), ('#8cc8ff', tint(MAIN, .6))] + [(n, tintN(n, MAIN)) for n in NAVY]
def recolor(s):
    for a, b in MAP:
        s = re.sub(re.escape(a), b, s, flags=re.I)
        ra, rb = rgb(a), rgb(b)
        s = re.sub(r'%d,\s*%d,\s*%d\b' % tuple(ra), '%d,%d,%d' % tuple(rb), s)
    return s
BLUE = re.compile('|'.join([re.escape(a) for a, _ in MAP] + [r'%d,\s*%d,\s*%d\b' % tuple(rgb(a)) for a, _ in MAP]), re.I)

def rules(css):
    """Top-level blocks: (prelude, body). Nested @media bodies are returned whole."""
    out, i, n = [], 0, len(css)
    css = re.sub(r'/\*.*?\*/', '', css, flags=re.S)
    n = len(css)
    while i < n:
        j = css.find('{', i)
        if j < 0: break
        pre = css[i:j].strip(); depth, k = 1, j + 1
        while depth and k < n:
            depth += css[k] == '{'; depth -= css[k] == '}'; k += 1
        out.append((pre, css[j + 1:k - 1])); i = k
    return out

def scoped(css):
    res = []
    for pre, body in rules(css):
        if pre.startswith('@keyframes'):
            continue
        if pre.startswith('@media'):
            inner = scoped(body)
            if inner: res.append(pre + '{' + inner + '}')
            continue
        if not BLUE.search(body): continue
        sels = []
        for s in pre.split(','):
            s = s.strip()
            # the card itself carries the class; the loading screen (.oil) is its next sibling
            if re.match(r'\.oidim(?![\w-])', s): sels.append('.oidim.oi--c1' + s[len('.oidim'):])
            elif re.match(r'\.oil(?![\w-])', s): sels.append('.oi--c1 ~ ' + s)
            elif s.startswith('.oil'): sels.append('.oi--c1 ~ .oil ' + s)
            else: sels.append('.oi--c1 ' + s)
        res.append(','.join(sels) + '{' + recolor(body) + '}')
    return '\n'.join(res)

if __name__ == '__main__':
    p = 'src/pages/the-build-blueprint.astro'; s = open(p).read(); a = s.index('<style is:global>')
    open(p, 'w').write(s[:a] + recolor(s[a:]))
    open('public/learn/x3-sent-build.css', 'w').write(recolor(open('public/learn/x3-sent.css').read()))
    p = 'src/views/sent/build.html'; s = recolor(open(p).read()).replace('/learn/x3-sent.css', '/learn/x3-sent-build.css'); open(p, 'w').write(s)
    open('src/styles/optin-build.css', 'w').write('/* Generated by scripts/recolor-build.py (9/11): the opt-in in C1 green, only with theme="c1" (Build page) */\n' + scoped(open('src/styles/optin.css').read()) + '\n.oi--c1 ~ .oil [style*="2997ff"]{color:' + MAIN + '!important}\n')
    print('ok', MAP[:4])
